//
// Exercise names do not say what they require. "Back Squat" mentions neither the
// barbell nor the rack, and only 16 of the 224 library names name any gear at
// all. So this is written by hand rather than sniffed from the name, and it is
// the reason a missing barbell yields a dumbbell bench press instead of a hole
// in the program.
//
// Each value is a list of REALIZATIONS in preference order:
//   gear — GEAR ids that must ALL be present (see GEAR in app.js)
//   tag  — the EXERCISE_MODIFIERS "Equipment" tag to stamp on the written
//          exercise, or null when the movement needs no modifier
//
// The builder takes the first realization the athlete's gear satisfies. Order
// matters: put the version you would actually program first.
//
// Two deliberate simplifications, so they read as decisions rather than gaps:
//   • "cable" stands for the cable stack AND selectorized machines. A gym with
//     a cable station has the machines; splitting them would double the
//     vocabulary to separate things that travel together.
//   • Cardio ergs with no icon of their own (assault bike, ski erg, stair
//     climber) carry an empty gear list. They map to almost no muscles, so the
//     builder rarely reaches for them and the looseness costs nothing.
//
// A tag must never repeat what the NAME already says, or the app renders
// "Cable Cable Fly". That is why Cable Fly, Lat Pulldown and Kettlebell Swing
// all carry null.
//
